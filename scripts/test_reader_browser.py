"""Browser regression for switching away from an unfinished PDF render.

Uses an isolated HTTP fixture and an actual PDF generated by Chromium.
This is not a substitute for accept_app.py's real model/native app checks.
"""
from __future__ import annotations

import json

from playwright.sync_api import sync_playwright
from test_app_backend import RUN, ApiTests


def check(value, message):
    if not value:
        raise AssertionError(message)


def main() -> None:
    from html_fixture import html_fixture, seed_html
    ApiTests.setUpClass()
    try:
        with sync_playwright() as pw:
            browser = pw.chromium.launch(headless=True, executable_path=pw.chromium.executable_path)
            try:
                writer = browser.new_page()
                writer.set_content('<h1>Reader regression fixture</h1><svg width="240" height="90"><rect x="5" y="5" width="220" height="70" fill="#dce8fa"/><path d="M10 65L80 20L140 50L210 15" fill="none" stroke="blue"/></svg>' + "<p>Selectable original PDF text with enough characters to highlight.</p>" * 55)
                pdf = writer.pdf(format="A4")
                writer.close()
                (ApiTests.vault / "papers_pdf" / "2510.16720.pdf").write_bytes(pdf)
                page = browser.new_page(viewport={"width": 404, "height": 642})
                errors = []
                page.on("pageerror", lambda error: errors.append(str(error)))
                page.goto(ApiTests.base + "/app")
                page.locator("[data-tab='notes']").click()
                page.locator(".note").first.click()
                page.locator("#paper-wrap .ls-text").first.wait_for()
                page.wait_for_function("!document.querySelector('#btn-hl').disabled")
                check(page.locator("#pdf-wrap canvas").count() == 0, "Default article still rendered PDF pages")
                before = page.locator("#paper-wrap").evaluate("el => parseFloat(getComputedStyle(el).fontSize)")
                page.locator("#reader-font-up").click()
                after = page.locator("#paper-wrap").evaluate("el => parseFloat(getComputedStyle(el).fontSize)")
                check(after > before, "Native text font size did not change")
                math = page.locator("#paper-wrap math").first
                check(math.evaluate("el => el.namespaceURI") == "http://www.w3.org/1998/Math/MathML", "MathML namespace was lost")
                fraction = page.locator("#paper-wrap mfrac").first.evaluate("el => [el.children[0].getBoundingClientRect().bottom,el.children[1].getBoundingClientRect().top]")
                check(fraction[0] <= fraction[1] + 1, "Native fraction was flattened")
                math.click()
                page.locator("#math-zoom[open]").wait_for()
                page.locator("#math-zoom-close").click()
                page.locator("#btn-hl").click()
                page.evaluate("""() => {
                  const el = [...document.querySelectorAll('#paper-pages [data-block]')].find(e => e.textContent.length > 25);
                  const range = document.createRange(); range.setStart(el.firstChild,0); range.setEnd(el.firstChild,20);
                  const selection = window.getSelection(); selection.removeAllRanges(); selection.addRange(range);
                  document.dispatchEvent(new MouseEvent('mouseup',{bubbles:true}));
                }""")
                page.locator("#paper-wrap mark").first.wait_for()
                page.locator("#paper-wrap figure img").first.wait_for()
                page.locator("#paper-wrap figure img").first.click()
                check(page.locator("#image-zoom").is_visible(), "Extracted figure did not open at native resolution")
                page.locator("#zoom-close").click()
                page.screenshot(path=str(RUN / "native-article.png"))
                page.locator("#btn-reader-close").click()
                page.locator(".note").first.click()
                page.locator("#paper-wrap mark").first.wait_for()
                page.locator("#btn-reader-note").click()
                page.locator("#note-md h2").first.wait_for()
                stalled = []
                page.route("**/api/pdf?*", lambda route: stalled.append(route))
                with page.expect_request("**/api/pdf?*"):
                    page.locator("#btn-reader-pdf").click()
                page.locator("#btn-reader-paper").click()
                check(page.locator("#btn-reader-pdf").is_enabled(), "Paper view left cancelled PDF comparison disabled")
                page.locator("#btn-reader-note").click()
                check(page.locator("#btn-hl").is_disabled(), "Highlight was enabled in Note view")
                check(page.locator("#btn-reader-pdf").is_enabled(), "Cancelled PDF load prevented returning to PDF")
                for route in stalled:
                    route.continue_()
                page.unroute("**/api/pdf?*")
                page.locator("#btn-reader-pdf").click()
                page.wait_for_function("!document.querySelector('#btn-hl').disabled")
                width = page.locator("#pdf-wrap .pg").first.evaluate("el => el.clientWidth")
                check(width > 320, f"PDF cached a tiny hidden-view render: {width}px")
                page.locator("#btn-hl").click()
                page.evaluate("""() => {
                  const span = [...document.querySelectorAll('.txtlayer span')].find(s => s.textContent.length > 15);
                  if (!span) throw Error('PDF text layer is missing');
                  const range = document.createRange(); range.selectNodeContents(span);
                  const selection = window.getSelection(); selection.removeAllRanges(); selection.addRange(range);
                  document.dispatchEvent(new MouseEvent('mouseup', {bubbles:true}));
                }""")
                page.locator("#pdf-wrap .hl").first.wait_for()
                page.screenshot(path=str(RUN / "reader-regression.png"))
                page.locator("#btn-reader-note").click()
                check(page.locator("#btn-hl").is_disabled(), "A completed render re-enabled Note-view highlighting")
                page.locator("#btn-reader-close").click()
                cached = page.request.get(ApiTests.base + "/api/paper?id=2510.16720&page=1").json()
                failed = [False]
                def html_retry(route):
                    body = cached if failed[0] else {"ok": False, "msg": "HTML unavailable regression"}
                    route.fulfill(status=200 if failed[0] else 503, content_type="application/json", body=json.dumps(body))
                    failed[0] = True
                page.route("**/api/paper?*", html_retry)
                page.locator(".note").first.click()
                page.locator("#paper-source-info").filter(has_text="HTML unavailable regression").wait_for()
                check(page.locator("#paper-pages math").count() == 0, "Failed HTML silently substituted broken PDF crops")
                page.locator("#paper-more").click()
                page.locator("#paper-pages math").first.wait_for()
                page.unroute("**/api/paper?*", html_retry)
                # A rejected annotation request from a closed paper must not
                # append its HTML or show an error over the newly opened paper.
                page.locator("#btn-reader-close").click()
                second_id = "2510.16721"
                seed_html(ApiTests.vault, second_id, html_fixture().replace(b"Left paragraph reader fixture", b"SECOND_PAPER_ONLY_MARKER"))
                (ApiTests.vault / "papers" / "second.md").write_text("# Second reader race\n\narXiv: " + second_id, encoding="utf-8")
                page.evaluate("refreshNotes()")
                stalled_marks = []
                page.route("**/api/reading-highlights?id=2510.16720", lambda route: stalled_marks.append(route))
                with page.expect_request("**/api/reading-highlights?id=2510.16720"):
                    page.locator(".note").filter(has_text="A real note").click()
                page.evaluate("() => { window._staleReaderLoad = paperState.loading; }")
                page.locator("#btn-reader-close").click()
                page.locator(".note").filter(has_text="Second reader race").click()
                page.locator("#paper-pages h1").filter(has_text="SECOND_PAPER_ONLY_MARKER").wait_for()
                check(len(stalled_marks) == 1, "Delayed annotation request was not intercepted")
                for route in stalled_marks:
                    route.fulfill(status=503, content_type="application/json", body=json.dumps({"ok": False, "msg": "STALE_MARKS_FAILURE"}))
                page.evaluate("async () => { await window._staleReaderLoad; }")
                check(page.locator("#paper-pages h1").count() == 1, "Stale paper HTML leaked into the current paper")
                check("STALE_MARKS_FAILURE" not in page.locator("#app-message").inner_text(), "A stale request displayed an error over the current paper")
                page.unroute("**/api/reading-highlights?id=2510.16720")
                check(not errors, f"JavaScript errors: {errors}")
                print(f"PASS: native reflow text/figures/zoom/font/highlight reopening; legacy PDF render cancellation; artifacts: {RUN}")
            finally:
                browser.close()
    finally:
        ApiTests.tearDownClass()


if __name__ == "__main__":
    main()
